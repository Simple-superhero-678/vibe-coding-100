// 异兽志 · 视图层 ⇄ 装配层之间的自定义事件名
//
// 为什么单开一个文件：这几个名字同时出现在「谁发」（detail.js / fav.js）和
// 「谁听」（main.js）两边。同一条字符串抄两份，迟早写岔 ——
// 少两个字、多个「请求」，事件就静默不响，而且不报错，最难查。
//
// 方向说明：视图层只派发，装配层只监听 + 执行。
// 视图层因此不需要知道「收藏存在哪」「导出是复制还是下载」，分层纪律（TECH_DESIGN §12.5）保持不变。

export const 打开请求 = '打开请求';   // 视图 → 装配：请打开这一条的详情（要播转场）
export const 关闭请求 = '关闭请求';   // 视图 → 装配：请收起当前面板
export const 收藏切换 = '收藏切换';   // 视图 → 装配：请切换这一条的收藏状态
export const 导出请求 = '导出请求';   // 视图 → 装配：请导出（detail.方式 = '复制' | '下载'）
