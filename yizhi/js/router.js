// 异兽志 · 路由层（Day 13）
//
// 职责只有一个：把「地址栏里那串 hash」和「站点此刻该显示什么」互相翻译。
// 这一层**不认识五部、不认识任何视图** ——「异兽」「境界」是装配层（main.js）的概念，
// 路由层只认「第一段是哪个词、后面跟着什么参数」。这样以后加第六部，
// 路由层一个字都不用改。
//
// ── 为什么用 hash，不用 history 真路径 ──────────────────────────────
// 站点挂在 GitHub Pages 上，那是纯静态托管，没有服务端 rewrite。
// 真路径（/异兽）刷新时会被当成「去找一个叫 异兽 的目录」，直接 404 ——
// 要救就得额外塞一份 404.html 并改部署流水线，为一个查阅站不值当。
// hash 的变化不发请求，刷新永远落在 index.html 上；而且 hash 变化天然进历史栈，
// 「返回上一页」白送（正好是今天的余力加练项）。
//
// ── 四条路由（Day 13）────────────────────────────────────────────
//   #/部/异兽         部内浏览（五部同式：神仙 / 神话 / 异兽 / 妖怪 / 境界）
//   #/搜/蛇           全站检索结果
//   #/藏              收藏
//   #/条/yishou-001   单条详情（余力加练：可分享的深链）
//   空 hash 或认不出来的，一律当默认入口 #/部/异兽。
//
// ── 一个必须知道的坑：replaceState 不触发 hashchange ─────────────────
// 「不想在历史里留痕」的场合（比如检索框每敲一个字符就更新地址）要用 换()，
// 而 换() 走的是 history.replaceState —— 浏览器**不会**为它派发 hashchange，
// 所以 换() 内部自己通知一次订阅者。漏了这一步，会出现「地址栏变了、页面没动」，
// 而且不报错，最难查。

/** 默认入口：认不出来时落到这里 */
const 默认 = Object.freeze({ 视图: '部', 参数: ['异兽'] });

/** 合法的视图名。多一个都要在这里登记 —— 不然拼错的手打地址会被静默吞掉 */
const 视图名 = Object.freeze(['部', '搜', '藏', '条']);

let 订阅者 = null;

/* 解码失败（手打的 % 不合法）不能把整个页面带崩，退回原文即可 */
function 解码(段) {
  try { return decodeURIComponent(段); } catch { return 段; }
}

/* 编码一段。
   为什么不直接用 encodeURIComponent：它会把「部」「异兽」「九尾狐」全变成
   %E9%83%A8… —— 地址栏是整个功能的门面，今天还要靠它截图，
   一串乱码等于白做。哈希里的非 ASCII 本来就是合法的，留着即可。
   真正必须编码的只有「会破坏结构或非法」的字符：斜杠、百分号、问号、井号、空格。 */
function 编段(值) {
  return String(值).replace(/[^\u0021-\u007E]|[\/%?#\[\]\\ ]/g, 字 => {
    const 码 = 字.codePointAt(0);
    return 码 > 127 ? 字 : encodeURIComponent(字);
  });
}

/* 滤掉空段：地址() 与 同址() 必须用同一套口径，否则「同址」判断会跟实际写入的地址对不上 */
function 净段(视图, 参数) {
  return [视图, ...参数].filter(项 => 项 != null && 项 !== '').map(String);
}

/**
 * 造一条 hash 字符串。参数里的中文原样保留，斜杠一类的结构字符才编码。
 * @returns {string} 形如 `#/部/异兽`
 */
export function 地址(视图, ...参数) {
  return '#/' + 净段(视图, 参数).map(编段).join('/');
}

/* 地址栏里那串 hash 是不是已经等于这个状态。
   不比字符串，比**解析结果** —— 浏览器可能把 hash 里的中文转成百分号形式存着
   （各家不完全一致），字符串比较会误判成「不同址」，于是一次点击塞一条重复历史。 */
function 同址(视图, 参数) {
  const 现在 = 读();
  return 现在.视图 === 视图
    && 现在.参数.join('\u0000') === 净段(视图, 参数).slice(1).join('\u0000');
}

/**
 * 读当前地址栏 → 路由对象。
 * @returns {{视图:string, 参数:string[]}} 认不出来一律给默认入口
 */
export function 读() {
  const 段 = location.hash.replace(/^#\/?/, '').split('/').filter(Boolean).map(解码);
  const [头, ...余] = 段;

  if (!视图名.includes(头)) return { 视图: 默认.视图, 参数: [...默认.参数] };

  switch (头) {
    case '部': return 余.length ? { 视图: '部', 参数: [余[0]] } : { 视图: '部', 参数: [...默认.参数] };
    /* 关键词里可能有斜杠（手打的），所以余下全部拼回去，不当路径分隔符看。
       空关键词（#/搜/）给空串 —— 是「退回去」还是「显示空结果」由装配层判，
       路由层不替它做产品决定。 */
    case '搜': return { 视图: '搜', 参数: [余.join('/')] };
    case '条': return 余.length ? { 视图: '条', 参数: [余[0]] } : { 视图: 默认.视图, 参数: [...默认.参数] };
    default:   return { 视图: '藏', 参数: [] };
  }
}

/**
 * 去某个状态：**新增一条历史**（前进后退能回到这里）。
 * 同址不重复入栈 —— 不然连点同一个 tab 会把历史塞满同一页。
 */
export function 去(视图, ...参数) {
  if (同址(视图, 参数)) return;
  location.hash = 地址(视图, ...参数);   // 这一步由浏览器派发 hashchange，订阅者会收到
}

/**
 * 换到某个状态但**不留痕**：给「输入即响应」的检索框用。
 * 每敲一个字符都 去() 的话，按一次后退键只退掉一个字符，人会被逼疯。
 */
export function 换(视图, ...参数) {
  if (同址(视图, 参数)) return;
  history.replaceState(null, '', 地址(视图, ...参数));
  通知();                    // replaceState 不派发 hashchange，自己补一次（见文件头）
}

/** 手动触发一次「重新按地址栏渲染」——replaceState 之后、启动补默认 hash 之后要用 */
export function 通知() {
  if (订阅者) 订阅者(读());
}

/** 订阅地址变化。全站只该有一个人订阅（装配层） */
export function 订阅(处理) {
  订阅者 = 处理;
  window.addEventListener('hashchange', () => 处理(读()));
}

/**
 * 启动时把「空 hash / 认不出来的 hash」归一化成合法地址。
 * 用 replaceState 不留痕：用户没做任何操作，历史里不该凭空多一条。
 */
export function 归一化() {
  const 路由 = 读();
  const 目标 = 地址(路由.视图, ...路由.参数);
  if (location.hash !== 目标) history.replaceState(null, '', 目标);
  return 路由;
}
