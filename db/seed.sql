-- =============================================================================
-- 自检（执行完本脚本后应看到的结果）
-- =============================================================================

-- 自检 1：每张核心表的行数 —— 期望 users = 5、favorites = 9
SELECT 'users'     AS table_name, count(*) AS row_count FROM public.users
UNION ALL
SELECT 'favorites' AS table_name, count(*) AS row_count FROM public.favorites;

-- 自检 2：两张表是怎么「拼」在一起的 —— 这就是今天的问题：
--         favorites.user_id  →  users.id
--         期望 9 行，第 1 列是人的昵称，第 3 列是他收的条目 id
SELECT u.nickname, u.provider, f.entry_id, f.created_at
FROM public.favorites AS f
JOIN public.users     AS u ON u.id = f.user_id
ORDER BY u.created_at, f.created_at;


