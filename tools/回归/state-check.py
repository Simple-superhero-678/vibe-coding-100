# -*- coding: utf-8 -*-
"""状态回归：十一档，验「加载中 / 成功 / 空 / 错误」四态在三个消费方都成立。

三个消费方：部浏览（#/部/x）· 全站检索（#/搜/词）· 收藏（#/藏）。
四态怎么造：本地调试开关 ?态=慢 / 错 / 空（只在 127.0.0.1 / localhost / file:// 生效）。

⚠️ 十一档**全部走探针**（探针/state.html）：--dump-dom 的取样点落在 load 那一刻，
而取数是异步的 —— 直接 dump 会同一档两轮红绿交替。探针在真实时间里轮询到渲染稳定，
把 视图台 / 收藏列表 / 站况 的文字抄进 data-result，判定留给本脚本。

跑法（在仓库根）：
    python tools/回归/state-check.py            # 全跑
    python tools/回归/state-check.py 1 6        # 只跑第 1–6 档
    python tools/回归/state-check.py 7 11       # 只跑第 7–11 档
一次全跑要起 11 个无头 Edge，可能顶到命令超时 —— 分两批更稳。
"""
import os
import re
import sys
from urllib.parse import urlencode

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _壳  # noqa: E402

端口 = 8147
探针 = '_probe-回归-state.html'
藏 = 'yishou-001,yaoguai-003'      # 预置两条收藏：异兽·九尾狐 + 妖怪·蜘蛛精

# 档 = (说明, 探针参数, [(含/不含, 片段), ...])
档单 = [
    ('成功 · 异兽部 12 卡', dict(路由='#/部/异兽'),
     [('含', '台class=grid'), ('含', '骨架=无'), ('含', '九尾狐'), ('含', '站况=异兽部 · 12 条')]),

    ('加载中 · 异兽部骨架', dict(态='慢', 路由='#/部/异兽'),
     [('含', '骨架=有'), ('含', '正在读取异兽部'), ('不含', '九尾狐')]),

    ('错误 · 异兽部没读到', dict(态='错', 路由='#/部/异兽'),
     [('含', '骨架=无'), ('含', '异兽部数据没读到'), ('含', '模拟读取失败'),
      ('含', '站况=异兽部 · 未读到数据')]),

    ('空 · 异兽部（出口＝重试）', dict(态='空', 路由='#/部/异兽'),
     [('含', '异兽部还是空的'), ('含', '重试'), ('不含', '异兽部数据没读到')]),

    ('空 · 神仙部（出口＝去异兽部）', dict(态='空', 路由='#/部/神仙'),
     [('含', '台class=stage'), ('含', '神仙部还是空的'), ('含', '去异兽部看看')]),

    ('错误 · 全站检索', dict(态='错', 路由='#/搜/蛇'),
     [('含', '五部数据都没读到'), ('含', '站况=全站 · 未读到数据')]),

    ('空 · 检索零结果（出口＝清空）', dict(态='空', 路由='#/搜/蛇'),
     [('含', '没找到「蛇」'), ('含', '清空，回到异兽部'), ('不含', '五部数据都没读到')]),

    ('空 · 收藏夹（出口＝去看异兽部）', dict(路由='#/藏'),
     [('含', '收藏夹还空着'), ('含', '去看异兽部'), ('含', '面板开=true')]),

    ('加载中 · 收藏面板骨架', dict(态='慢', 路由='#/藏', 预置=藏),
     [('含', '骨架=有'), ('含', '正在读取收藏'), ('含', '面板开=true')]),

    ('错误 · 收藏面板没读到', dict(态='错', 路由='#/藏', 预置=藏),
     [('含', '收藏夹没读到数据'), ('含', '「异兽、妖怪」部的数据没读到'), ('不含', '此条已下架')]),

    ('成功 · 收藏列表 2 条真条目', dict(路由='#/藏', 预置=藏),
     [('含', '骨架=无'), ('含', '九尾'), ('含', '蜘蛛精'), ('不含', '此条已下架')]),
]


def 探针地址(**参):
    # 用 urlencode 而不是手拼：路由里的 # 必须被编码，否则会被当成探针页自己的 hash
    return 探针 + '?' + urlencode({k: v for k, v in 参.items() if v})


_壳.自查()
_壳.装探针('state.html', 探针)
服务 = _壳.造服务(端口, 卡住='/__never')

起 = int(sys.argv[1]) if len(sys.argv) > 1 else 1
止 = int(sys.argv[2]) if len(sys.argv) > 2 else len(档单)

败 = 0
try:
    for 序号, (说明, 参, 断言们) in enumerate(档单, 1):
        if 序号 < 起 or 序号 > 止:
            continue

        try:
            html = _壳.取页(探针地址(**参), 端口, 预算=4000)
        except Exception as 错:
            败 += 1
            print(f'  ✗   [{序号}] {说明}｜取页失败：{错}', flush=True)
            continue

        现场 = _壳.取结果(html)
        差 = _壳.断言(现场, 断言们)
        if 差:
            败 += 1
            安全名 = re.sub(r'[^\w\u4e00-\u9fa5]+', '_', 说明)
            p = _壳.存现场(f'状态-{序号}-{安全名}.html', html)
            print(f'  ✗   [{序号}] {说明}｜{"、".join(差)}\n      现场：{现场[:200]}\n      已存 {p}', flush=True)
        else:
            print(f'  OK  [{序号}] {说明}｜{现场[:76]}', flush=True)
finally:
    _壳.撤探针(探针)

sys.exit(_壳.收尾(服务, 败))
